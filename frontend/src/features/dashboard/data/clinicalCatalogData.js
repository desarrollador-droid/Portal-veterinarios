/**
 * Busca exámenes clínicos por término de búsqueda y categoría
 */
export function searchClinicalExams(query = '', category = 'all') {
  let list = CLINICAL_EXAMS;
  if (category && category !== 'all') {
    list = list.filter((e) => e.categoria === category || e.categoria.toLowerCase().includes(category.toLowerCase()));
  }
  if (!query || !query.trim()) {
    return list;
  }
  const q = query.trim().toLowerCase();
  return list.filter((e) => {
    return (
      e.nombre.toLowerCase().includes(q) ||
      (e.observaciones && e.observaciones.toLowerCase().includes(q)) ||
      (e.muestra && e.muestra.toLowerCase().includes(q)) ||
      (e.categoria && e.categoria.toLowerCase().includes(q)) ||
      String(e.precio).includes(q)
    );
  });
}

/**
 * Obtiene un examen por su ID
 */
export function getClinicalExamById(id) {
  return CLINICAL_EXAMS.find((e) => e.id === id) || null;
}

export default {
  CLINICAL_CATEGORIES,
  CLINICAL_EXAMS,
  searchClinicalExams,
  getClinicalExamById,
};
